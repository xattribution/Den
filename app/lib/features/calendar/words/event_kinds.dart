/// A word matches at the start of a word and, unless it ends in `*`, as the whole word or its
/// plural or -ing form: "games" and "lessons" match, "business" is not a bus.
final Map<String, RegExp> _patterns = {
  for (final (word, _) in _words)
    word: word.endsWith('*')
        ? RegExp('(^|[^a-z])${RegExp.escape(word.substring(0, word.length - 1))}')
        : RegExp('(^|[^a-z])${RegExp.escape(word)}(s|es|ing)?([^a-z]|\$)'),
};

/// The kind of event [title] (then [location], then the [category] icon) names: a key of
/// `Pictograms.events`, or `calendar` when nothing does.
String eventKind(String title, {String location = '', String? category}) {
  for (final text in [title, location]) {
    final t = text.toLowerCase();
    if (t.isEmpty) continue;
    for (final (word, kind) in _words) {
      if (_patterns[word]!.hasMatch(t)) return kind;
    }
  }
  return _categories[category] ?? 'calendar';
}
